async def main() -> None:
    print(f"총 {len(QUERIES)}개 질문 검색 테스트\n")
    hit, miss = 0, 0
    for i, q in enumerate(QUERIES, 1):
        res = await search(q, namespaces=["terms"], top_k=2)
        chunks = res["ranked_chunks"]
        print(f"[{i:02d}] {q[:46]}…")
        if not chunks:
            miss += 1
            print("     ✗ 결과 없음")
            continue
        hit += 1
        for c in chunks:
            txt = " ".join(c["text"].split())[:60]
            print(f"     · {c['product_name']} {c.get('article_number') or ''} | {txt}")
        print()
    print(f"\n요약: 결과있음 {hit} / 결과없음 {miss} / 총 {len(QUERIES)}")
    await close_pool()


if __name__ == "__main__":
    asyncio.run(main())
